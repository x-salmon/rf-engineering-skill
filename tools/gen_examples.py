def run(cmd):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        rfcalc.main(shlex.split(cmd))
    return buf.getvalue().rstrip()


def main():
    lines = ["# Worked examples", "",
             "Generated by `tools/gen_examples.py`: every output below is real program output.", ""]
    for title, cmd in EXAMPLES:
        lines += [f"## {title}", "", "```console", f"$ rfcalc.py {cmd}", run(cmd), "```", ""]
    path = os.path.join(ROOT, "docs", "examples.md")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {path} ({len(EXAMPLES)} examples)")


if __name__ == "__main__":
    main()
